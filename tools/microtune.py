"""Microtuning tables for mods/microtune-st.

A tuning is 12 offsets from 12-TET, in tenths of a cent, one per semitone
above the tuning's root (step 0 is always 0), repeating every octave. This
tool holds the factory tunings, converts Scala .scl files and writes the C
table mods/microtune-st/tunings.h.

    python tools/microtune.py --check            # tunings.h matches the definitions
    python tools/microtune.py --write            # regenerate tunings.h
    python tools/microtune.py scale.scl          # print a .scl as offsets
    python tools/microtune.py scale.scl --c NAME # ... as a C initializer
"""
import argparse
from fractions import Fraction
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'mods/microtune-st/tunings.h'
LIMIT = 1000                 # |offset| <= 100.0 cents; the map's arithmetic relies on it
NAME_MAX = 12                # characters, shown on the device


def cents(value):
    """Cents of a Scala pitch line: a ratio (3/2, 2) or cents (701.955)."""
    v = value.split()[0]
    if '.' in v:
        return float(v)
    r = Fraction(v)
    if r <= 0:
        raise ValueError('ratio must be positive: ' + value)
    return 1200 * math.log2(r)


def offsets(steps_cents):
    """12 pitches above the root (step 0 included), in cents -> offsets in 0.1 cent."""
    if len(steps_cents) != 12:
        raise ValueError('a tuning has 12 steps, got %d' % len(steps_cents))
    out = [int(round((c - 100 * i) * 10)) for i, c in enumerate(steps_cents)]
    if out[0] != 0:
        raise ValueError('step 0 must be the root (offset 0)')
    bad = [i for i, o in enumerate(out) if abs(o) > LIMIT]
    if bad:
        raise ValueError('steps %s are more than 100 cents from 12-TET' % bad)
    return out


def parse_scl(text):
    """A Scala file -> (description, 12 offsets). Needs 12 notes and a 2/1 octave."""
    lines = [l.strip() for l in text.splitlines() if not l.strip().startswith('!')]
    lines = [l for l in lines]
    desc, count = lines[0], int(lines[1].split()[0])
    pitches = [cents(l) for l in lines[2:2 + count]]
    if count != 12:
        raise ValueError('only 12-note scales map onto 12 steps (this one has %d)' % count)
    if abs(pitches[-1] - 1200) > 1e-6:
        raise ValueError('the 12th pitch must be the octave, 2/1 (got %.3f cents)' % pitches[-1])
    return desc, offsets([0.0] + pitches[:-1])


def ratios(*rs):
    return [cents(r) for r in rs]


def fifths(fifth, low=-3):
    """A chain of 12 fifths of `fifth` cents, from `low` fifths below the root."""
    pc = {}
    for n in range(low, low + 12):
        c = (n * fifth) % 1200
        pc[round(c / 100) % 12] = c if round(c / 100) < 12 else c - 1200
    return [pc[i] for i in range(12)]


QCM = 1200 * math.log2(5) / 4                         # quarter-comma meantone fifth

# Factory tunings, in this order on the device. Sources: standard published
# values; Poole Rod 12 from poole-rod12tone.scl (Scale Workshop).
FACTORY = [
    ('12-TET', [100 * i for i in range(12)]),
    ('JUST MAJOR', ratios('1', '16/15', '9/8', '6/5', '5/4', '4/3', '45/32', '3/2', '8/5', '5/3', '16/9', '15/8')),
    ('JUST MINOR', ratios('1', '16/15', '10/9', '6/5', '5/4', '4/3', '45/32', '3/2', '8/5', '5/3', '9/5', '15/8')),
    ('PYTHAGOREAN', ratios('1', '256/243', '9/8', '32/27', '81/64', '4/3', '729/512', '3/2', '128/81', '27/16',
                           '16/9', '243/128')),
    ('MEANTONE 1/4', fifths(QCM, -3)),
    ('WERCKM. III', [0, 90.225, 192.180, 294.135, 390.225, 498.045, 588.270, 696.090, 792.180, 888.270, 996.090,
                     1092.180]),
    ('KIRNB. III', [0, 90.225, 193.157, 294.135, 386.314, 498.045, 590.224, 696.578, 792.180, 889.735, 996.090,
                    1088.269]),
    ('VALLOTTI', [0, 94.135, 196.090, 298.045, 392.180, 501.955, 592.180, 698.045, 796.090, 894.135, 1000.0,
                  1090.225]),
    ('ARABIC RAST', [0, 100, 200, 300, 350, 500, 600, 700, 800, 900, 1000, 1050]),
    ('POOLE ROD12', ratios('1', '33/32', '9/8', '7/6', '14/11', '4/3', '11/8', '3/2', '14/9', '27/16', '7/4',
                           '11/6')),
]


def factory():
    out = []
    for name, steps in FACTORY:
        assert len(name) <= NAME_MAX, name
        out.append((name, offsets(steps)))
    return out


def header():
    rows = ['/* SPDX-License-Identifier: GPL-2.0-or-later',
            ' * Generated by tools/microtune.py --write: do not edit. Offsets from 12-TET in',
            ' * tenths of a cent, step 0 (the root) to 11. */',
            '#ifndef MICROTUNE_TUNINGS_H', '#define MICROTUNE_TUNINGS_H',
            '#define MT_FACTORY %d' % len(FACTORY), '#define MT_NAME %d' % (NAME_MAX + 1),
            'static const char mt_factory_name[MT_FACTORY][MT_NAME] = {']
    t = factory()
    rows += ['    "%s",' % n for n, _ in t] + ['};', 'static const short mt_factory[MT_FACTORY][12] = {']
    rows += ['    {%s}, /* %s */' % (', '.join('%d' % o for o in offs), n) for n, offs in t]
    rows += ['};', '#endif', '']
    return '\n'.join(rows)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('scl', nargs='?', type=Path)
    p.add_argument('--c', metavar='NAME')
    p.add_argument('--write', action='store_true')
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    if a.write:
        HEADER.write_text(header())
        print('wrote', HEADER.relative_to(ROOT))
    if a.check:
        if HEADER.read_text() != header():
            raise SystemExit('tunings.h is out of date: run tools/microtune.py --write')
        print('tunings.h matches the %d factory tunings' % len(FACTORY))
    if a.scl:
        desc, offs = parse_scl(a.scl.read_text(errors='replace'))
        if a.c:
            print('{"%s", {%s}}' % (a.c[:NAME_MAX].upper(), ', '.join(str(o) for o in offs)))
        else:
            print(desc)
            for i, o in enumerate(offs):
                print('%2d  %+7.1f cents' % (i, o / 10))


if __name__ == '__main__':
    main()
